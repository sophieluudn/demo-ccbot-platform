const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1835, height: 910 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('file:///C:/Users/user/Desktop/demo-ccbot-platform/index.html#conversation-records');
  await page.locator('.records-table .el-table__row').first().waitFor();
  const box = await page.locator('#records-app').boundingBox();
  if (box.y !== 50) throw Error('Records outside viewport');
  await page.getByRole('button', { name: '搜尋', exact: true }).click();
  if (await page.locator('.records-table .el-table__row').count() !== 3) throw Error('Missing records');
  await page.locator('.records-table').getByRole('button', { name: '查看對話' }).first().click();
  await page.locator('.record-dialog').waitFor({ state: 'visible' });
  await page.locator('.record-dialog .el-dialog__headerbtn').click();
  await page.locator('#keyword-settings-link').click();
  await page.getByRole('button', { name: '新增字詞群組', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '新增字詞群組', exact: true });
  await dialog.waitFor({ state: 'visible' });
  await page.waitForTimeout(350);
  await page.screenshot({ path: '.qa/modal-desktop.png' });
  await dialog.getByPlaceholder('請輸入說明文字').fill('驗證群組');
  await dialog.getByPlaceholder('請輸入說明字詞').fill('第一字詞');
  await dialog.getByRole('button', { name: '新增', exact: true }).click();
  const tag = dialog.locator('.keyword-word-tags .el-tag');
  if (!(await tag.getAttribute('class')).includes('el-tag--danger')) throw Error('Word tag should be red');
  await dialog.getByPlaceholder('請輸入說明字詞').fill('第二字詞');
  await dialog.getByRole('button', { name: '確定', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  if (!(await page.locator('.keyword-table').innerText()).includes('第一字詞,第二字詞')) throw Error('Words not saved');
  await page.locator('#conversation-records-link').click();
  await page.locator('#records-app').waitFor({ state: 'visible' });
  await page.screenshot({ path: '.qa/records-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.qa/records-mobile.png' });
  await page.locator('#keyword-settings-link').click();
  await page.getByRole('button', { name: '新增字詞群組', exact: true }).click();
  await dialog.waitFor({ state: 'visible' });
  await page.waitForTimeout(350);
  await page.screenshot({ path: '.qa/modal-mobile.png' });
  if (errors.length) throw Error(errors.join('\n'));
  console.log('PASS: real Chrome records visibility/search/detail, keyword modal/add words/save, route return, desktop/mobile; no browser errors');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
